"""
Topic: Comparison Operators

- >, <, >=, <=
- ==, !=
- 비교 연산의 결과는 항상 True 또는 False
"""


# --- Greater Than (>) | 크다 ---

a = 10
b = 5

print("a > b:", a > b)


# --- Less Than (<) | 작다 ---

print("a < b:", a < b)


# --- Greater Than or Equal (>=) | 크거나 같다 ---

print("a >= 10:", a >= 10)


# --- Less Than or Equal (<=) | 작거나 같다 ---

print("b <= 5:", b <= 5)


# --- Equal (==) | 같다 ---

x = 7
y = 7

print("x == y:", x == y)


# --- Not Equal (!=) | 같지 않다 ---

print("x != y:", x != y)


# --- String Comparison | 문자열 비교 ---

text1 = "apple"
text2 = "banana"

print("text1 == text2:", text1 == text2)


# 💡 Learned
# 1. 비교 연산자의 결과는 항상 bool (True / False)이다.
# 2. == 는 값이 같은지 비교한다.
# 3. 문자열도 비교 연산이 가능하다.
