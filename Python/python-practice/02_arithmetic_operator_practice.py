"""
Topic: Arithmetic Operators

- + (덧셈)
- - (뺄셈)
- * (곱셈)
- / (나눗셈)
- // (몫)
- % (나머지)
- ** (거듭제곱)
"""


# --- Addition (+) | 덧셈 ---

a = 10
b = 3

print("a + b =", a + b)


# --- Subtraction (-) | 뺄셈 ---

print("a - b =", a - b)


# --- Multiplication (*) | 곱셈 ---

print("a * b =", a * b)


# --- Division (/) | 나눗셈 (항상 float 반환) ---

print("a / b =", a / b, "| Type:", type(a / b))


# --- Floor Division (//) | 몫 ---

print("a // b =", a // b, "| Type:", type(a // b))


# --- Modulus (%) | 나머지 ---

print("a % b =", a % b)


# --- Exponent (**) | 거듭제곱 ---

print("a ** b =", a ** b)


# --- Arithmetic with Float | 실수 연산 ---

x = 5
y = 2.0

print("x + y =", x + y, "| Type:", type(x + y))


# 💡 Learned
# 1. / 는 항상 float을 반환한다.
# 2. // 는 몫을 반환한다.
# 3. % 는 나머지를 반환한다.
# 4. ** 는 거듭제곱 연산자이다.
# 5. int와 float 연산 시 float으로 자동 형 변환된다.
