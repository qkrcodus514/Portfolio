# --- Variable Declaration | 변수 선언 ---

age = 20
height = 175.5
name = "Python"


# --- Type Inspection | 자료형 확인 ---

print("Age Type:", type(age))
print("Height Type:", type(height))
print("Name Type:", type(name))


# --- Arithmetic Operation | 산술 연산 ---

age = age + 1
print("Updated Age (Next Year):", age)


